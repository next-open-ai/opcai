const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('opcaiDesktop', {
  pickFile: () => ipcRenderer.invoke('opcai:pick-file'),
  pickProjectDirectory: () => ipcRenderer.invoke('opcai:pick-project-directory'),
  createProjectWorkspace: (value) => ipcRenderer.invoke('opcai:create-project-workspace', value),
  listProjectFiles: (root) => ipcRenderer.invoke('opcai:list-project-files', root),
  readProjectFile: (root, relative) => ipcRenderer.invoke('opcai:read-project-file', root, relative),
  writeProjectFile: (root, relative, content) => ipcRenderer.invoke('opcai:write-project-file', root, relative, content),
  syncProjectWorkspace: (root, runId) => ipcRenderer.invoke('opcai:sync-project-workspace', root, runId),
  materializeProjectAssets: (root, assetIds) => ipcRenderer.invoke('opcai:materialize-project-assets', root, assetIds),
  registerPreviewRoot: (root) => ipcRenderer.invoke('opcai:register-preview-root', root),
  registerAssetPreviewRoot: (assetId) => ipcRenderer.invoke('opcai:register-asset-preview-root', assetId),
  readProjectPreview: (root, relative) => ipcRenderer.invoke('opcai:read-project-preview', root, relative),
  readAssetPreview: (assetId) => ipcRenderer.invoke('opcai:read-asset-preview', assetId),
  revealProjectFile: (root, relative) => ipcRenderer.invoke('opcai:reveal-project-file', root, relative),
  openAssetInBrowser: (assetId) => ipcRenderer.invoke('opcai:open-asset-in-browser', assetId),
  openProjectFileInBrowser: (root, relative) => ipcRenderer.invoke('opcai:open-project-file-in-browser', root, relative),
  pickSkill: () => ipcRenderer.invoke('opcai:pick-skill'),
  createSkill: (skill) => ipcRenderer.invoke('opcai:create-skill', skill),
  writeSkillDraft: (draft) => ipcRenderer.invoke('opcai:write-skill-draft', draft),
  readSkillDraft: (path) => ipcRenderer.invoke('opcai:read-skill-draft', path),
  listSkillFiles: (path) => ipcRenderer.invoke('opcai:list-skill-files', path),
  readSkillFile: (path) => ipcRenderer.invoke('opcai:read-skill-file', path),
  writeSkillFile: (path, content) => ipcRenderer.invoke('opcai:write-skill-file', path, content),
  deleteManagedSkill: (path) => ipcRenderer.invoke('opcai:delete-managed-skill', path),
  installSkill: (reference) => ipcRenderer.invoke('opcai:install-skill', reference),
  importGitSkill: (url) => ipcRenderer.invoke('opcai:import-git-skill', url),
  findSkills: (query, batchCount) => ipcRenderer.invoke('opcai:find-skills', query, batchCount),
  openExternal: (url) => ipcRenderer.invoke('opcai:open-external', url),
  getModelConfig: () => ipcRenderer.invoke('opcai:get-model-config'),
  saveModelConfig: (config) => ipcRenderer.invoke('opcai:save-model-config', config),
  getSearchConfig: () => ipcRenderer.invoke('opcai:get-search-config'),
  saveSearchConfig: (config) => ipcRenderer.invoke('opcai:save-search-config', config),
  testProvider: (value) => ipcRenderer.invoke('opcai:test-provider', value),
  listProviderModels: (value) => ipcRenderer.invoke('opcai:list-provider-models', value),
  listOllamaModels: (baseUrl) => ipcRenderer.invoke('opcai:list-ollama-models', baseUrl),
  pullOllamaModel: (baseUrl, modelName) => ipcRenderer.invoke('opcai:pull-ollama-model', baseUrl, modelName),
  storageGet: (key) => ipcRenderer.invoke('opcai:storage-get', key),
  storageSet: (key, value) => ipcRenderer.invoke('opcai:storage-set', key, value),
  listAssets: () => ipcRenderer.invoke('opcai:list-assets'),
  archiveArtifact: (artifact) => ipcRenderer.invoke('opcai:archive-artifact', artifact),
  linkAssetsToProject: (value) => ipcRenderer.invoke('opcai:link-assets-to-project', value),
  unlinkAssetsFromProject: (assetIds) => ipcRenderer.invoke('opcai:unlink-assets-from-project', assetIds),
  saveAsset: (assetId) => ipcRenderer.invoke('opcai:save-asset', assetId),
  revealAsset: (assetId) => ipcRenderer.invoke('opcai:reveal-asset', assetId),
});
